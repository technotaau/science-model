# Join the generated sentences into one audio file with natural pauses, and write the timeline
# (subtitle text + which model part virtual Avni points at) to site/avni-ai.js.
import json, re, subprocess, wave
import numpy as np
speech = json.load(open("speech.json")); report = json.load(open("report.json"))
SR = 24000
GAP_SENT, GAP_SEC = 0.35, 0.9
RULES = [  # first match wins; None = she looks at the judges
    (r"Good morning|Thank you|Jai Hind!$|So, what can|Let me show you|best waste is the waste we never create\.$", None),
    (r"Ram Ghat|Rapti|dustbins", "mountain"),
    (r"Remember my first line", "boards"),
    (r"toilet|ODF|Swachh Bharat|launched", "swachh"),
    (r"biogas plant|microbes", "biogas"),
    (r"segregat|Wet waste|Dry waste|Mixed waste|Separated waste|separating", "bins"),
    (r"compost|biogas", "biogas"),
    (r"eco-brick|Single-use plastic", "bins"),
    (r"Plastic Man|roads|Padma", "city"),
    (r"7Rs|3Rs|Refuse|best waste", "boards"),
    (r"diesel|vapour|hydrogen|Jind", "train"),
    (r"Green energy|Solar|sun|gigawatt|clean air", "city"),
    (r"wind", "windmill"),
    (r"burnt|steam|turbine|energy", "wte"),
    (r"filter|stones|charcoal|cotton|clearer|layer", "filter"),
    (r"Factories|effluent", "factory"),
    (r"sewage|rivers|puja|river", "wwt"),
    (r"water", "mountain"),
]
DEFAULT = {"s-open": None, "s-sbm": "swachh", "s-waste": "bins", "s-plastic": "bins", "s-7r": "boards", "s-wte": "wte", "s-green": "city", "s-water": "filter", "s-close": None}
def part_for(sec, t):
    if sec == "s-close": return None  # conclusion: no pointing, only eye contact with the judges
    for pat, p in RULES:
        if re.search(pat, t, re.I): return p
    return DEFAULT.get(sec)
chunks, segs, t = [], [], 0.0
for si, sec in enumerate(speech):
    for i, sent in enumerate(sec["sentences"]):
        with wave.open("seg_%s-%d.wav" % (sec["id"], i)) as w:
            a = np.frombuffer(w.readframes(w.getnframes()), dtype=np.int16)
        chunks.append(a); d = len(a) / SR
        segs.append({"start": round(t, 2), "end": round(t + d, 2), "text": sent, "part": part_for(sec["id"], sent), "section": sec["title"]})
        t += d
        gap = GAP_SEC if i == len(sec["sentences"]) - 1 else GAP_SENT
        chunks.append(np.zeros(int(gap * SR), dtype=np.int16)); t += gap
full = np.concatenate(chunks)
with wave.open("avni-ai.wav", "wb") as w:
    w.setnchannels(1); w.setsampwidth(2); w.setframerate(SR); w.writeframes(full.tobytes())
subprocess.run(["ffmpeg", "-hide_banner", "-loglevel", "error", "-y", "-i", "avni-ai.wav", "-af", "loudnorm=I=-18:TP=-2", "-c:a", "aac", "-b:a", "48k", "/home/user/science-model/site/media/avni-ai-speech.m4a"], check=True)
words = sum(len(s["text"].split()) for s in segs)
js = ("/* Avni's full stage speech in an AI voice made from her own Malerkotla recording (XTTS-v2, Coqui Public Model\n"
      "   License 1.0.0, non-commercial: https://huggingface.co/coqui/XTTS-v2/blob/main/LICENSE.txt). Made for practice\n"
      "   with her family's permission (7 Nov 2026). NOT a real recording of Avni. Generated by scratchpad avni/assemble.py. */\n"
      "window.AVNI_AI = " + json.dumps({"src": "media/avni-ai-speech.m4a", "seconds": round(t, 1), "wpm": round(words / (t / 60)), "segments": segs}, ensure_ascii=False, indent=0) + ";\n")
open("/home/user/science-model/site/avni-ai.js", "w", encoding="utf8").write(js)
print("total", round(t, 1), "s;", words, "words;", round(words / (t / 60)), "wpm;", len(segs), "sentences")
